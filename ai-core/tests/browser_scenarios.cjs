const {chromium}=require('playwright');
const assert=require('assert');
const fs=require('fs');
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 const p=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
 p.on('pageerror',e=>errors.push(e.message));
 const base=process.env.WEMEET_TEST_URL||'http://127.0.0.1:8011';
 await p.goto(base+'/scenarios');await p.waitForFunction(()=>document.querySelectorAll('.scenario').length===20);
 assert.match(await p.locator('#counts').textContent(),/작성 200개/);
 await p.locator('#domain').selectOption('design');await p.waitForFunction(()=>document.querySelector('#pageInfo').textContent.includes('20개'));
 await p.locator('.scenario').first().click();await p.waitForSelector('#detail h2');
 assert.match(await p.locator('#detail').textContent(),/기준안 · AI 미실행/);
 assert.match(await p.locator('#detail').textContent(),/기본 \/ 변형 비교/);
 assert.ok((await p.locator('#detail .bubble').count())>=6);
 await p.screenshot({path:'ai-core/runs/scenario-library.png',fullPage:false});
 const old=await p.request.get(base+'/ai/v1/workspaces').then(r=>r.json());
 await p.getByRole('button',{name:'대화부터 시작 · 새 작업',exact:true}).click();
 await p.waitForURL(/workspace=/);await p.waitForFunction(()=>typeof workspaceReady!=='undefined'&&workspaceReady);
 assert.ok((await p.evaluate(()=>state.groupChat.length))>=6);
 assert.ok(await p.evaluate(()=>state.scenarioId.startsWith('design')));
 const newer=await p.request.get(base+'/ai/v1/workspaces').then(r=>r.json());
 assert.equal(newer.length,old.length+1);for(const work of old)assert.ok(newer.some(v=>v.id===work.id));
 const savedId=await p.evaluate(()=>state.workspaceId);await p.reload();await p.waitForFunction(()=>workspaceReady);
 assert.equal(await p.evaluate(()=>state.workspaceId),savedId);
 await p.goto(base+'/scenarios');await p.waitForSelector('.scenario');await p.locator('#domain').selectOption('exam');await p.waitForTimeout(250);
 await p.locator('.scenario').first().click();await p.waitForSelector('#detail h2');
 await p.getByRole('button',{name:'지정 단계 입력 불러오기 · 호출 없음',exact:true}).click();await p.waitForURL(/scenario-entry=1/);
 await p.waitForFunction(()=>typeof workspaceReady!=='undefined'&&workspaceReady);await p.waitForTimeout(1800);
 assert.ok(await p.evaluate(()=>Boolean(state.scenarioEntry)));
 assert.ok((await p.locator('#request').inputValue()).length>100);
 assert.deepEqual(errors,[]);
 fs.writeFileSync('ai-core/runs/browser-scenarios-report.json',JSON.stringify({passed:true,assertions:['200 visible','domain filter','base-variant comparison','multi-turn preview','new workspace preserves existing work','reload restore','authored stage input loaded with no API call'],errors},null,2));
 await browser.close();console.log('Scenario browser smoke passed');
})().catch(e=>{console.error(e);process.exit(1)});
