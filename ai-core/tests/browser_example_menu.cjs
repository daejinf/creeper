const {chromium}=require('playwright');
const assert=require('assert');
const fs=require('fs');
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 const page=await browser.newPage({acceptDownloads:true}),errors=[],modelPosts=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('request',r=>{if(r.method()==='POST'&&/\/ai\/v1\/(coach$|analyze$|group-plan$|member-plan$|member-goal\/|goal-spec\/draft)/.test(r.url()))modelPosts.push(r.url())});
 const base=process.env.WEMEET_TEST_URL||'http://127.0.0.1:8010';
 await page.goto(base);await page.waitForFunction(()=>workspaceReady&&exampleCatalog.length===200);
 await page.locator('.toolbar details summary').first().click();
 assert.equal(await page.locator('#example option[value^="scenario:"]').count(),200);
 assert.equal(await page.locator('#example option[value="project"]').count(),1);
 await page.locator('#exampleDomain').selectOption('course');
 assert.equal(await page.locator('#example option[value^="scenario:"]').count(),20);
 await page.locator('#exampleSearch').fill('course-03-v');
 assert.equal(await page.locator('#example option[value^="scenario:"]').count(),1);
 await page.locator('#example').selectOption('scenario:course-03-v');
 const old=await page.evaluate(()=>state.workspaceId);
 await page.locator('#loadExample').click();await page.waitForFunction(id=>state.workspaceId!==id,old);
 assert.equal(await page.evaluate(()=>state.scenarioId),'course-03-v');
 assert.ok((await page.evaluate(()=>state.groupChat.length))>=6);
 assert.equal(await page.evaluate(()=>state.runs.length),0);
 const original=await page.request.get(base+'/ai/v1/workspaces/'+old);assert.equal(original.status(),200);
 const downloadEvent=page.waitForEvent('download');await page.locator('#saveExampleJson').click();
 const download=await downloadEvent;assert.equal(download.suggestedFilename(),'course-03-v.json');
 const path=await download.path(),scenario=JSON.parse(fs.readFileSync(path,'utf8'));
 assert.equal(scenario.kind,'VARIANT');assert.ok(scenario.private_conversations);
 const beforeImport=await page.evaluate(()=>state.workspaceId);
 await page.locator('#file').setInputFiles({name:'scenario.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(scenario))});
 await page.waitForFunction(id=>state.workspaceId!==id,beforeImport);
 assert.equal(await page.evaluate(()=>state.scenarioId),scenario.case_id);
 const afterImport=await page.evaluate(()=>state.workspaceId);
 await page.locator('#file').setInputFiles({name:'invalid.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({case_id:'bad',group_input:{}}))});
 await page.waitForFunction(()=>!document.querySelector('#error').hidden);
 assert.equal(await page.evaluate(()=>state.workspaceId),afterImport);
 await page.locator('#exampleSearch').fill('');await page.locator('#exampleDomain').selectOption('');
 await page.locator('#example').selectOption('project');await page.locator('#loadExample').click();
 await page.waitForFunction(()=>Boolean(state.draft)&&!state.scenarioId);
 assert.equal(modelPosts.length,0);assert.deepEqual(errors,[]);
 fs.writeFileSync('ai-core/runs/browser-example-menu-report.json',JSON.stringify({passed:true,checks:['200 scenarios in existing dropdown','domain and search filters','legacy examples retained','load preserves previous workspace','selected JSON download','scenario JSON reimport','invalid JSON preserves current work','no model POST on load/export/import'],modelPosts,errors},null,2));
 await browser.close();console.log('Example menu / JSON browser tests passed');
})().catch(e=>{console.error(e);process.exit(1)});
